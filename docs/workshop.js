(() => {
  'use strict';
  const root = document.querySelector('[data-workshop]');
  if (!root) return;
  const el = (tag, text, attrs = {}) => {
    const node = document.createElement(tag);
    if (text !== null) node.textContent = text;
    for (const [key, value] of Object.entries(attrs)) node.setAttribute(key, value);
    return node;
  };
  const prefix = 'seeds-workshop-v1:';
  const memory = new Map();
  let current, area, status, modules;
  let storageAvailable = true;
  function persist() {
    if (!current || !area) return;
    memory.set(current.id, area.value);
    try {
      localStorage.setItem(prefix + current.id, area.value);
      storageAvailable = true;
      status.textContent = 'Draft saved in this browser only. Export Markdown to keep or move it. No vault changes made.';
    } catch (_) {
      storageAvailable = false;
      status.textContent = 'Browser storage unavailable. This draft is held only in this open page. Export now to preserve it.';
    }
  }
  function download(text, name) {
    const url = URL.createObjectURL(new Blob([text], {type: 'text/markdown;charset=utf-8'}));
    const a = el('a', '', {href: url, download: name});
    document.body.append(a); a.click(); a.remove(); setTimeout(() => URL.revokeObjectURL(url), 1000);
  }
  function show(id, focus = false) {
    persist();
    current = modules.find(m => m.id === id) || modules[0];
    root.replaceChildren();
    const label = el('label', 'Choose one decision packet', {for: 'workshop-module'});
    const select = el('select', null, {id: 'workshop-module'});
    modules.forEach(m => select.append(el('option', `${m.id} · ${m.title}`, {value:m.id})));
    select.value = current.id;
    select.addEventListener('change', () => {
      const url = new URL(location.href); url.searchParams.set('module',select.value); url.hash='session'; history.replaceState(null,'',url); show(select.value,true);
    });
    const heading=el('h2',`${current.id} · ${current.title}`,{tabindex:'-1'});
    const gate=el('p',current.gate,{class:'workshop-gate'});
    status=el('p','Drafts are local to this browser. Export before switching device or clearing site data.',{role:'status','aria-live':'polite'});
    const detail=el('details',null,{class:'packet-detail'});
    detail.append(el('summary','Read sources, alternatives, scene test, and completion checklist (spoilers)'));
    // HTML is generated by the repository's escaping Markdown renderer, never from user input.
    const packet=el('div',null,{class:'reading'}); packet.innerHTML=current.html; detail.append(packet);
    area=el('textarea',null,{id:'workshop-answer',spellcheck:'true'});
    const template=`Module: ${current.id} · ${current.title}\nGate: ${current.gate}\nState: DRAFT\n\nAuthor answer:\n\nExact restatement:\n\nSelected option or new answer:\n\nTradeoffs and rejected alternatives:\n\nPrerequisites resolved / deferred:\n\nScene test and adversarial result:\n\nRemaining uncertainty:\n\nExplicit acceptance (leave blank until confirmed):\n\nAffected notes and QA decision reference:\n`;
    let saved=memory.get(current.id);
    if (saved === undefined) {try {saved=localStorage.getItem(prefix+current.id);} catch (_) {storageAvailable=false;}}
    area.value=saved ?? template;
    area.addEventListener('input',persist);
    if(!storageAvailable) status.textContent='Browser storage unavailable. Export Markdown to preserve this draft.';
    const exportButton=el('button','Export answer as Markdown',{type:'button'});
    exportButton.addEventListener('click',()=>{persist();download(area.value,`seeds-workshop-${current.id}-answer.md`);});
    const sourceButton=el('button','Download source packet',{type:'button',class:'secondary'});
    sourceButton.addEventListener('click',()=>download(current.markdown,`seeds-workshop-${current.id}-source.md`));
    const importInput=el('input',null,{type:'file',id:'workshop-import',accept:'.md,.txt,text/markdown,text/plain'});
    importInput.addEventListener('change',async()=>{
      const file=importInput.files[0];if(!file)return;
      if(file.size>1024*1024){status.textContent='Choose a Markdown answer under 1 MB.';return;}
      try {
        const text=await file.text();
        const idMatch=text.match(/^Module:\s*(?:WS-)?(\d{2})\b/m);
        if(idMatch && idMatch[1]!==current.id){status.textContent=`That answer belongs to module ${idMatch[1]}. Select that module first.`;return;}
        if(!confirm('Replace the current draft with this file? Export your current answer first if you want to keep both.'))return;
        area.value=text;persist();
      }catch(_){status.textContent='The file could not be read. Your existing draft is unchanged.';}
    });
    const toolbar=el('div',null,{class:'workshop-toolbar'});toolbar.append(exportButton,sourceButton);
    const accepted=String(current.status||'').startsWith('author-accepted');
    const stateText=accepted ? 'Author gate accepted · Open mechanics remain labeled.' : 'Author gate open · All alternatives are proposals.';
    root.append(label,select,heading,el('p',stateText+' Prerequisites: '+current.prerequisites),gate,el('label',accepted?'Further development notes':'Your answer and decision notes',{for:'workshop-answer'}),area,toolbar,status,el('label','Restore an exported answer',{for:'workshop-import'}),importInput,detail);
    if(focus)heading.focus();
  }
  fetch(root.dataset.source).then(r=>{if(!r.ok)throw Error('unavailable');return r.json();}).then(data=>{
    modules=data.modules;
    if(!Array.isArray(modules)||!modules.length)throw Error('empty');
    show(new URL(location.href).searchParams.get('module')||modules[0].id);
  }).catch(()=>{root.replaceChildren(el('p','The interactive packets could not load. Use the Markdown source links below or open the workshop in the repository. No answers have been changed.',{role:'alert'}));});
})();
